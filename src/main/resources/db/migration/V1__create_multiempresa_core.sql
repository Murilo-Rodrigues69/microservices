create table empresa (
    id bigint generated by default as identity primary key,
    nome varchar(120) not null,
    cnpj varchar(14) not null,
    razao_social varchar(255) not null,
    nome_fantasia varchar(255),
    inscricao_estadual varchar(30) not null,
    serie varchar(10) not null,
    natureza_operacao varchar(255) not null,
    cep varchar(8) not null,
    logradouro varchar(255) not null,
    numero varchar(30) not null,
    bairro varchar(120) not null,
    codigo_municipio varchar(10) not null,
    descricao_municipio varchar(120) not null,
    uf varchar(2) not null,
    modelo varchar(10) not null,
    ambiente varchar(20) not null,
    certificado_pfx_path varchar(500) not null,
    certificado_senha varchar(255) not null,
    cadeia_jks_path varchar(500) not null,
    cadeia_senha varchar(255) not null,
    csc varchar(255),
    csc_id integer,
    ativo boolean not null default true,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);

create unique index uk_empresa_cnpj on empresa(cnpj);

create table produto_empresa (
    id bigint generated by default as identity primary key,
    empresa_id bigint not null,
    descricao varchar(255) not null,
    codigo_barras varchar(20),
    ncm varchar(10),
    cest varchar(10),
    origem varchar(30),
    cfop varchar(10),
    unidade_comercial varchar(10),
    preco_unitario_sugerido numeric(19, 2),
    ativo boolean not null default true,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    constraint fk_produto_empresa_empresa foreign key (empresa_id) references empresa(id)
);

create index idx_produto_empresa_empresa on produto_empresa(empresa_id);

create table cliente_empresa (
    id bigint generated by default as identity primary key,
    empresa_id bigint not null,
    nome varchar(255) not null,
    cpf_cnpj varchar(14) not null,
    cep varchar(8) not null,
    logradouro varchar(255),
    numero varchar(30),
    bairro varchar(120),
    codigo_municipio varchar(10),
    descricao_municipio varchar(120),
    uf varchar(2),
    email varchar(255),
    ativo boolean not null default true,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    constraint fk_cliente_empresa_empresa foreign key (empresa_id) references empresa(id)
);

create unique index uk_cliente_empresa_documento on cliente_empresa(empresa_id, cpf_cnpj);
create index idx_cliente_empresa_empresa on cliente_empresa(empresa_id);
