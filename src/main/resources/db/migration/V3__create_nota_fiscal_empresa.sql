create table nota_fiscal_empresa (
    id bigint generated by default as identity primary key,
    empresa_id bigint not null,
    cliente_empresa_id bigint,
    modelo varchar(10) not null,
    situacao varchar(30) not null,
    numero_nota varchar(20),
    serie varchar(10),
    chave_acesso varchar(44) not null,
    protocolo_autorizacao varchar(50),
    c_stat integer,
    motivo varchar(2000),
    qr_code_url varchar(2000),
    destinatario_nome varchar(255),
    destinatario_documento varchar(14),
    valor_total numeric(19, 2),
    data_emissao timestamp,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    constraint fk_nota_fiscal_empresa_empresa foreign key (empresa_id) references empresa(id),
    constraint fk_nota_fiscal_empresa_cliente foreign key (cliente_empresa_id) references cliente_empresa(id)
);

create unique index uk_nota_fiscal_empresa_chave on nota_fiscal_empresa(chave_acesso);
create index idx_nota_fiscal_empresa_empresa_data on nota_fiscal_empresa(empresa_id, data_emissao desc, id desc);
create index idx_nota_fiscal_empresa_cliente on nota_fiscal_empresa(cliente_empresa_id);
